#!/usr/bin/env python3
"""Identify a smooth piano parameter field from the ten locked training notes.

No waveform, impulse response or held-out measurement is embedded in the synth.
The generated header contains physical losses/tuning and a radiation projection.
"""
import argparse
import json
from pathlib import Path
import numpy as np
from scipy.ndimage import gaussian_filter1d

ROOT=Path(__file__).resolve().parents[1]
N=64
NOTES=[36,48,60,72,84]

def regularized(values,weights,fallback,strength=2.0):
    values=np.asarray(values,float);weights=np.asarray(weights,float)
    y=np.where(weights>0,values,fallback)
    D=np.diff(np.eye(N),2,axis=0)
    W=np.diag(weights+.03)
    return np.linalg.solve(W+strength*D.T@D,W@y)

def generate_header(profile):
    def a(x):return '{'+','.join(f'{float(z):.12g}' for z in x)+'}'
    rows=[]
    for k in profile['keys']:
        rows.append('{'+','.join([str(k['midi']),str(k['f1_hz']),str(k['B']),str(k['hardness']),str(k['velocity_exponent']),str(k['detune_scale']),a(k['sigma_late']),a(k['sigma_prompt']),a(k['radiation_db']),a(k.get('radiation_after_db',k['radiation_db']))])+'}')
    content='''// Generated by tools/fit_calibration.py from the locked TRAIN10 only.
#pragma once
#include <array>
namespace piano_calibration {
constexpr int partials=64;
struct Anchor {int note;double f1,B,hardness,velocityExponent,detuneScale;
 std::array<double,partials> late,prompt,radiationDb,radiationAfterDb;};
constexpr bool radiationEnabled='''+('true' if profile.get('radiation_enabled') else 'false')+''';
constexpr std::array<Anchor,5> anchors={{
'''+',\n'.join(rows)+'''\n}};
} // namespace piano_calibration
'''
    (ROOT/'src/calibration.h').write_text(content)

def mechanics():
    refs=json.loads((ROOT/'benchmark/reference_features.json').read_text())['samples']
    train=[r for r in refs if r['split']=='train']
    assert len(train)==10 and all(r['layer'] in (4,12) and r['midi'] in NOTES for r in train)
    keys=[]
    # This smooth shape is only a weak prior where a recorded partial is too
    # quiet or too irregular to identify a meaningful loss.
    for note,vel_exp,detune in zip(NOTES,[.69,.70,.86,.74,.78],[1.0,1.0,1.2,1.5,2.5]):
        rr=[r for r in train if r['midi']==note]
        f1=float(np.median([r['f1_hz'] for r in rr]));B=float(np.median([r['B'] for r in rr]))
        late=[];prompt=[];wl=[];wp=[]
        for n in range(1,N+1):
            ls=[];ps=[];lw=[];pw=[]
            for r in rr:
                pp=next((p for p in r['partials'] if p['n']==n),None)
                if not pp:continue
                if pp['relative_db'][0] < -45:continue
                for name,vals,weights in [('late',ls,lw),('early',ps,pw)]:
                    d=pp['decay'].get(name)
                    if d and d['slope_db_per_second']<-.3:
                        q=max(0.0,d['r_squared'])
                        if q<.15:continue
                        vals.append(np.clip(d['amplitude_sigma_per_second'],.06,15));weights.append(q)
            fallback=.12+.10*(f1/261.6)**.7+.025*n**1.4
            late.append(float(np.average(ls,weights=lw)) if ls else fallback)
            prompt.append(float(np.average(ps,weights=pw)) if ps else max(fallback,.35+.32*(f1/261.6)**.5+.04*n**1.3))
            wl.append(sum(lw));wp.append(sum(pw))
        fallback=np.array([.12+.10*(f1/261.6)**.7+.025*n**1.4 for n in range(1,N+1)])
        late=np.exp(regularized(np.log(late),wl,np.log(fallback),.65))
        prompt=np.exp(regularized(np.log(prompt),wp,np.log(fallback*2),.65))
        late=np.clip(late,.08,14)
        prompt=np.clip(np.maximum(prompt,late*1.1),.12,18)
        keys.append({'midi':note,'f1_hz':f1,'B':B,'hardness':1.0,'velocity_exponent':vel_exp,'detune_scale':detune,
                     'sigma_late':late.tolist(),'sigma_prompt':prompt.tolist(),'radiation_db':[0.0]*N})
    profile={'version':2,'training_ids':sorted(r['id'] for r in train),'radiation_enabled':False,'keys':keys,
             'identification':'Robust phase-insensitive training measurements; positive smooth loss priors; no held-out data used.',
             'notes':'sigma_prompt is total initial amplitude decay; sigma_late sets intrinsic loss; their difference drives a passive common-unison port.'}
    (ROOT/'benchmark/calibration.json').write_text(json.dumps(profile,indent=2)+'\n')
    generate_header(profile)
    print('Generated measured mechanics from',profile['training_ids'])

def radiation():
    profile=json.loads((ROOT/'benchmark/calibration.json').read_text())
    proposal=json.loads((ROOT/'benchmark/radiation_fit.json').read_text())
    if proposal.get('heldout_measurements_used') is not False or set(profile['training_ids'])!=set(proposal['training_ids']):
        raise ValueError('Radiation proposal must use exactly the locked training set')
    for key in profile['keys']:
        fit=next(k for k in proposal['keys'] if k['midi']==key['midi'])
        for source,target in [('radiation_db','radiation_db'),('radiation_secondary_db','radiation_after_db')]:
            values=fit[source]
            if len(values)!=N or not np.isfinite(values).all():
                raise ValueError('Invalid radiation profile')
            key[target]=values
    profile['radiation_enabled']=True
    profile['radiation_fit']='radiation_fit.json; two positive observation magnitudes fitted jointly to locked TRAIN10 only'
    (ROOT/'benchmark/calibration.json').write_text(json.dumps(profile,indent=2)+'\n')
    generate_header(profile)

def main():
    ap=argparse.ArgumentParser();ap.add_argument('stage',choices=['mechanics','radiation','header']);args=ap.parse_args()
    if args.stage=='mechanics':mechanics()
    elif args.stage=='radiation':radiation()
    else:generate_header(json.loads((ROOT/'benchmark/calibration.json').read_text()))
if __name__=='__main__':main()
